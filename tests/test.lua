-- 本测试仅使用 Lua 5.1 语法，可由所有支持的解释器执行。
local dir = assert(arg[1], "module directory required")
package.cpath = dir .. "/?.so;" .. dir .. "/?.dll;" .. package.cpath
local log = require("luaspdlog")
local function eq(a, b) assert(a == b, tostring(a) .. " ~= " .. tostring(b)) end
local function rejects(fn)
  local ok, err = pcall(fn)
  assert(not ok and type(err) == "string", "expected Lua error")
end
local function read(path)
  local f = assert(io.open(path, "rb"))
  local s = f:read("*a"); f:close(); return s
end
eq(log._VERSION, "0.1.0")
assert(log._SPDLOG_VERSION:match("^1%.17%."))
eq(log.get("missing"), nil)
rejects(function() log.info("no default") end)
local console = log.create("default")
eq(console:name(), "default")
console:set_level("off")
log.info("suppressed")
console:close()
log.shutdown()
local path = "integration.log"
local l = log.create("test", {type="file", filename=path, truncate=true, pattern="%v", level="trace"})
eq(log.get_default():name(), "test")
eq(log.get("test"):name(), "test")
rejects(function() log.create("test") end)
local payload = "literal {braces} 100% 中文\0tail"
l:info(payload)
l:set_level("warn")
eq(l:level(), log.level.warn)
eq(l:should_log("info"), false)
l:info("filtered")
log.warn("warning")
l:log(log.level.error, "error")
l:flush()
local content = read(path)
assert(content:find(payload, 1, true))
assert(not content:find("filtered", 1, true))
assert(content:find("warning", 1, true))
assert(content:find("error", 1, true))
eq(l:last_error(), nil)
rejects(function() l.info({}, "invalid self") end)
l:set_pattern("%v", "utc")
l:flush_on("warn")
l:enable_backtrace(3)
l:debug("backtrace-only")
l:dump_backtrace()
l:disable_backtrace()
l:flush()
assert(read(path):find("backtrace-only", 1, true))
for _, bad in ipairs({-1, 7, 1.5, "bogus", false, {}}) do
  rejects(function() l:set_level(bad) end)
end
rejects(function() l:info({}) end)
rejects(function() l:set_pattern("%v", "bad") end)
rejects(function() log.create("bad\0name") end)
rejects(function() log.create("bad", {type="file", filename="bad\0path"}) end)
rejects(function() log.create("bad", {type="nonsense", filename="x"}) end)
rejects(function() log.create("bad", {type="file"}) end)
rejects(function() log.create("bad", {sinks={}}) end)
rejects(function() log.create("bad", {color="yes"}) end)
rejects(function() log.create("bad", {overflow="other"}) end)
rejects(function() log.create("bad", {type="rotating", filename="x", max_size=0}) end)
rejects(function() log.create("bad", {type="daily", filename="x", hour=24}) end)
for i=1,1000 do rejects(function() l:set_level("invalid") end) end
eq(log.drop("test"), true)
eq(log.get("test"), nil)
l:warn("handle survives drop")
log.set_default(l)
log.error("default still works")
l:close(); l:close()
rejects(function() l:info("closed") end)
rejects(function() log.info("closed default") end)
os.remove(path)
local a, b = "multi-a.log", "multi-b.log"
local multi = log.create("multi", {pattern="%v", level="trace", sinks={
  {type="file", filename=a, truncate=true},
  {type="file", filename=b, truncate=true, level="error"}
}})
multi:info("one"); multi:error("two"); multi:flush()
assert(read(a):find("one", 1, true)); assert(not read(b):find("one", 1, true))
assert(read(b):find("two", 1, true))
multi:close(); os.remove(a); os.remove(b)
local rotating = log.create("rotate", {type="rotating", filename="rotate.log", max_size=128, max_files=2, pattern="%v"})
for i=1,100 do rotating:info(string.rep("x", 50)) end
rotating:flush(); assert(#read("rotate.1.log") > 0)
rotating:close()
os.remove("rotate.log"); os.remove("rotate.1.log"); os.remove("rotate.2.log")
local daily = log.create("daily", {type="daily", filename="daily.log", pattern="%v"})
daily:info("daily"); daily:flush(); daily:close()
local daily_path = "daily_" .. os.date("%Y-%m-%d") .. ".log"
assert(read(daily_path):find("daily", 1, true)); os.remove(daily_path)
log.shutdown()
local full = io.open("/dev/full", "rb")
if full then
  full:close()
  local disk = log.create("disk-error", {type="file", filename="/dev/full"})
  disk:info("write failure"); disk:flush()
  assert(type(disk:last_error(true)) == "string")
  eq(disk:last_error(), nil)
  disk:close(); log.shutdown()
end
log.init_thread_pool(64, 1)
rejects(function() log.init_thread_pool(64) end)
local async = log.create("async", {type="file", filename="async.log", truncate=true, async=true, pattern="%v"})
for i=1,2000 do async:info("message-" .. i) end
async:flush()
log.drop_all()
log.shutdown() -- 等待后台线程写完，并使已移出注册表的句柄失效。
local data = read("async.log")
local _, count = data:gsub("message%-", "")
eq(count, 2000)
assert(data:find("message-2000", 1, true))
rejects(function() async:flush() end)
os.remove("async.log")
log.init_thread_pool(2, 1)
local overrun = log.create("overrun", {type="null", async=true, overflow="overrun_oldest"})
for i=1,10000 do overrun:info("stress") end
log.shutdown()
local reused = log.create("test", {type="null"})
eq(reused:name(), "test")
log.shutdown()
collectgarbage("collect")
print("integration: OK (" .. _VERSION .. ")")
